/**
 * Generate documentation screenshot inventory from screenshots/image-manifest.json.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const rootDir = resolve( dirname( fileURLToPath( import.meta.url ) ), '..' );
const manifestPath = resolve( rootDir, 'screenshots/image-manifest.json' );
const outPath = resolve( rootDir, 'screenshots/INVENTORY.md' );

const manifest = JSON.parse( readFileSync( manifestPath, 'utf8' ) );

/** @type {Array<{ id: string, title: string, description?: string, embed: { doc?: string, path: string, alt: string, status: string } }>} */
const docImages = manifest.images
	.filter( ( entry ) => entry.use === 'docs' && entry.embed?.doc )
	.sort( ( a, b ) => a.id.localeCompare( b.id ) );

/**
 * @param {string} docPath Repo-root-relative markdown path.
 */
function docPageLink( docPath ) {
	const docRelative = relative( dirname( outPath ), resolve( rootDir, docPath ) ).replace(
		/\\/g,
		'/'
	);
	const label = basename( docPath, '.md' );
	return `[${ label }](${ docRelative })`;
}

/**
 * @param {string} assetPath Repo-root-relative asset path.
 */
function embedRelativePath( assetPath ) {
	return relative( dirname( outPath ), resolve( rootDir, assetPath ) ).replace(
		/\\/g,
		'/'
	);
}

/**
 * @param {string} docPath
 */
function docSectionTitle( docPath ) {
	const name = basename( docPath, '.md' );
	if ( name === 'README' ) {
		const parent = basename( dirname( docPath ) );
		return parent === 'user-guide' ? 'User guide' : parent;
	}
	return name
		.split( '-' )
		.map( ( part ) => part.charAt( 0 ).toUpperCase() + part.slice( 1 ) )
		.join( ' ' );
}

/** @type {Map<string, typeof docImages>} */
const byDoc = new Map();
for ( const entry of docImages ) {
	const doc = entry.embed.doc;

	if ( ! doc ) {
		continue;
	}

	if ( ! byDoc.has( doc ) ) {
		byDoc.set( doc, [] );
	}
	byDoc.get( doc ).push( entry );
}

const sortedDocs = [ ...byDoc.keys() ].sort( ( a, b ) => a.localeCompare( b ) );

const sections = sortedDocs.map( ( docPath ) => {
	const entries = byDoc.get( docPath ) ?? [];
	const title = docSectionTitle( docPath );
	const link = docPageLink( docPath );

	const rows = entries
		.sort( ( a, b ) => a.id.localeCompare( b.id ) )
		.map( ( entry ) => {
			const assetRel = embedRelativePath( entry.embed.path );
			const assetAbs = resolve( rootDir, entry.embed.path );
			const hasFile = existsSync( assetAbs );
			const status =
				entry.embed.status === 'captured' && hasFile
					? 'captured'
					: entry.embed.status;

			return [
				`### ${ entry.title }`,
				'',
				`![${ entry.embed.alt }](${ assetRel })`,
				'',
				`| Field | Value |`,
				`| --- | --- |`,
				`| Manifest ID | \`${ entry.id }\` |`,
				`| Status | ${ status } |`,
				`| Doc | ${ link } |`,
				`| Alt text | ${ entry.embed.alt } |`,
				entry.description
					? `| Description | ${ entry.description } |`
					: '',
				'',
			].join( '\n' );
		} );

	return [ `## ${ title }`, '', `Used in ${ link }.`, '', ...rows ].join(
		'\n'
	);
} );

const body = [
	'# Screenshot inventory (contributor)',
	'',
	'<!-- Generated by scripts/sync-screenshots-docs.mjs — edit screenshots/image-manifest.json instead. -->',
	'',
	'Internal reference for doc screenshots. User-facing guides live under `docs/user-guide/`.',
	'',
	...sections,
].join( '\n' );

writeFileSync( outPath, body, 'utf8' );
console.log(
	`Synced screenshots inventory → ${ outPath } (${ docImages.length } entries)`
);
